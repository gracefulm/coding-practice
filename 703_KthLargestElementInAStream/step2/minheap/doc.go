package step2

/*
package step2は、最小ヒープを使って解く方法です。

---

最小ヒープ（min-heap）は、最小値をすぐ取り出せるようにしたデータ構造です。中身を完全には並べ替えず、「親は子以下」という条件だけを守ります。そうすることで、追加と削除を O(log n) で行います。

構造

最小ヒープは、次の2つの条件を満たす二分木です。

1. 完全二分木：上の段から順に、各段を左から詰めて要素を入れていきます。
2. ヒープ条件：どの親も、自分の子以下の値を持ちます。その結果、根（一番上）が必ず最小値になります。

        1
      /   \
     3     2
    / \   /
   7   4 5

ヒープ条件は「親と子」の間の関係だけです。兄弟どうしや、別の枝にある要素どうしの大小は決まっていません。上の図でも、3 と 2 の大小関係は左右の位置と関係ありません。全体をソートしないので、操作が安く済みます。

配列での表し方

完全二分木は隙間なく詰まっているので、ポインタを使わずに配列にそのまま入れられます。

index:  0  1  2  3  4  5
value: [1, 3, 2, 7, 4, 5]

インデックス i の要素について、親と子の位置は計算で求まります。

- 親：(i-1)/2
- 左の子：2i+1
- 右の子：2i+2

基本操作

┌─────────────────────────────────┬───────────────────────────────────────────────────────────────────────────────────────────────────┬──────────┐
│              操作                │                                               方法                                                │  計算量   │
├─────────────────────────────────┼───────────────────────────────────────────────────────────────────────────────────────────────────┼──────────┤
│ 最小値を見る                      │ h[0] を見るだけ                                                                                     │ O(1)     │
├─────────────────────────────────┼───────────────────────────────────────────────────────────────────────────────────────────────────┼──────────┤
│ 追加（Push）                     │ 末尾に入れ、親より小さい間は親と入れ替えて上へ移動（sift up）                                              │ O(log n) │
├─────────────────────────────────┼───────────────────────────────────────────────────────────────────────────────────────────────────┼──────────┤
│ 最小値の削除（Pop）                │ 根と末尾を入れ替えて末尾を取り除き、新しい根を小さいほうの子と入れ替えながら下へ移動（sift down）                │ O(log n) │
├─────────────────────────────────┼───────────────────────────────────────────────────────────────────────────────────────────────────┼──────────┤
│ 配列からヒープを作る（heapify）     │ 後ろ半分の親から順に下へ移動させる                                                                      │ O(n)     │
└─────────────────────────────────┴───────────────────────────────────────────────────────────────────────────────────────────────────┴──────────┘

木の高さは log n なので、上へ・下へ移動する処理は最大でも log n 回で終わります。

例：上の図のヒープに 0 を追加する

[1,3,2,7,4,5,0]   末尾(index 6)に追加。親は index 2 の 2
[1,3,0,7,4,5,2]   0 < 2 なので入れ替え。親は index 0 の 1
[0,3,1,7,4,5,2]   0 < 1 なので入れ替え。根に着いたので終了
*/
